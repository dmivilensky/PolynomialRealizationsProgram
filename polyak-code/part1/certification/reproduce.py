"""Cold mathematical verification and deterministic JSON-only packaging."""
from pathlib import Path
import hashlib
import io
import lzma
import shutil
import tarfile

from .paths import ROOT, MATH, GENERATED, HEAVY_BALL, PROOF
from .report import Collector, VerificationError, canonical_bytes
from .verify import write_json, source_hashes, requirements_hash, verify


def integrity_controls():
    """Exercise exact-data rejection and precision restoration failure paths."""
    from .certificates.schema import validate, polynomial
    import sympy as s
    from flint import ctx as arb_context
    import mpmath as mp
    from .precision import local_precision
    result = Collector("certification-controls")
    try:
        Collector("negative-control").check(False, "deliberate false identity")
    except VerificationError:
        rejected = True
    else:
        rejected = False
    result.check(rejected, "a false exact check causes failure")
    try:
        validate({"variables": ["z"], "terms": [["2/4", [1]]]})
    except ValueError:
        rejected = True
    else:
        rejected = False
    result.check(rejected, "noncanonical exact data are rejected")
    try:
        polynomial(s.Float("0.1") * s.Symbol("x"), [s.Symbol("x")])
    except ValueError:
        rejected = True
    else:
        rejected = False
    result.check(rejected, "floating coefficients cannot become exact source data")
    previous = (arb_context.prec, mp.mp.dps)

    @local_precision(bits=113, digits=37)
    def scoped_failure():
        if (arb_context.prec, mp.mp.dps) != (113, 37):
            raise ValueError("precision context did not enter")
        raise ArithmeticError("intentional precision cleanup control")

    try:
        scoped_failure()
    except ArithmeticError:
        pass
    result.check((arb_context.prec, mp.mp.dps) == previous,
                 "precision is restored after a failed calculation")
    return result.result()


def regenerate(output=None, jobs=4, slabs=4000, profile="proof"):
    """Recompute checks and mathematical JSON; plotting remains separate."""
    from .export import export_bundle, check_bundle
    if slabs != 4000:
        raise ValueError("exact export requires 4000 slabs per continued family")
    if profile not in ("proof", "complete") or not 1 <= jobs <= 8:
        raise ValueError("use profile proof/complete and 1..8 jobs")
    output = Path(output or GENERATED).expanduser().resolve()
    protected = (ROOT, PROOF, HEAVY_BALL)
    if any(output == path or output in path.parents for path in protected):
        raise ValueError("regeneration output would contain sources or published proof data")
    if ROOT in output.parents and output != GENERATED:
        raise ValueError("use generated or an output directory outside the package")
    marker = output / ".heavy-ball-certification-generated"
    if output.exists() and any(output.iterdir()) and not marker.is_file():
        raise ValueError("refusing to clean an unmarked nonempty output directory")
    if output.exists():
        shutil.rmtree(output)
    output.mkdir(parents=True)
    marker.write_text("Generated by Heavy-Ball Part I certification regen\n")
    verified = verify(output / "verification", jobs, slabs, profile=profile)
    if not verified["passed"]:
        raise RuntimeError("cold verification failed; inspect verification reports")
    controls = integrity_controls()
    write_json(output / "controls.json", controls)
    exported = export_bundle(output / "math", output / "verification")
    checked = check_bundle(output / "math")
    archive = package(None if output == GENERATED else output / "proof.tar.xz",
                      mathematics=output / "math")
    result = {"schema": "heavy-ball-certification-regeneration-v1", "passed": True,
              "historical": False, "verification": verified["passed"],
              "profile": profile, "controls": controls["passed"], "bundle": checked,
              "export": exported, "archive": archive, "sources_sha256": source_hashes(),
              "requirements_sha256": requirements_hash(), "bundle_directory": "math"}
    write_json(output / "regeneration.json", result)
    return result


def package(output=None, mathematics=None):
    """Archive only mathematical JSON, preserving its recorded evidence scope."""
    from .export import read_bundle, check_bundle
    mathematics = Path(mathematics or MATH).expanduser().resolve()
    check_bundle(mathematics)
    manifest, payloads = read_bundle(mathematics)
    if manifest.get("provenance", {}).get("verification_scope") == "current-producer":
        producer = manifest.get("producer", {})
        if (producer.get("sources_sha256") != source_hashes() or
            producer.get("requirements_sha256") != requirements_hash()):
            raise ValueError("producer sources changed after export; regenerate the mathematical data")
    schema = (PROOF / "schema.json").read_bytes()
    if payloads["schema.json"] != schema:
        raise ValueError("published schema changed; export the mathematical data again")
    payloads["manifest.json"] = canonical_bytes(manifest)
    target = Path(output or PROOF / "proof.tar.xz").expanduser().resolve()
    protected = [PROOF / "schema.json", PROOF / "README.md", PROOF / "manifest.json"]
    protected += [mathematics / name for name in payloads]
    if target in protected:
        raise ValueError("archive output would overwrite a source data member")
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w", format=tarfile.USTAR_FORMAT) as archive:
        for name, raw in sorted(payloads.items()):
            info = tarfile.TarInfo(name)
            info.size, info.mode, info.mtime = len(raw), 0o644, 0
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            archive.addfile(info, io.BytesIO(raw))
    raw = lzma.compress(buffer.getvalue(), format=lzma.FORMAT_XZ, preset=6)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(raw)
    if target == PROOF / "proof.tar.xz":
        (PROOF / "manifest.json").write_bytes(payloads["manifest.json"])
    return {"archive": target.name, "members": len(payloads), "bytes": len(raw),
            "sha256": hashlib.sha256(raw).hexdigest(),
            "verification_scope": manifest.get("provenance", {}).get("verification_scope", "unspecified")}
