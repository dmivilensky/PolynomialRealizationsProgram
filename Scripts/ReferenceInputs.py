"""Regenerate only exact defining inputs for the 1.000013 reference proof."""
import sys
sys.dont_write_bytecode=True
import argparse
import hashlib
import json
from pathlib import Path
from FetchCertificate import ROOT,fetch,load_source
from SourceWitnesses import install_source
from PrepareCertificate import prepare_payload,numeric_tokens,exact_number


def literal(text):
    """
    Quote a string as a Lean-compatible literal for provenance fields in the generated source.
    """
    return json.dumps(text, ensure_ascii=False)


def raw_bytes(text):
    """
    Emit the original ASCII bytes as a literal natural-number list. Keeping bytes lets Lean
    check tokenization rather than trust Python's decoding.
    """
    return "["+",".join(map(str,text.encode("ascii")))+"]"


def list_of(values):
    """
    Serialize a sequence of already-rendered Lean terms into a list literal.
    """
    return "["+",".join(values)+"]"


def number_chunks(text, limit=64):
    """
    Split the input at line boundaries into small numeric-token groups. Small independent
    DecodedBytes obligations limit kernel-reduction memory.
    """
    current, count = [], 0
    for line in text.splitlines(keepends=True):
        size = len(numeric_tokens(line))
        if current and count+size>limit:
            yield "".join(current)
            current, count = [], 0
        current.append(line); count += size
    if current:
        yield "".join(current)


def decoded_fields(text):
    """
    Emit exact token bytes, rational values, source bytes and kernel-decidable
    decoding/tokenization fields. The generated DecodedBytes structure checks both
    representations.
    """
    tokens = numeric_tokens(text)
    values = [exact_number(t) for t in tokens]
    return ("  tokens := "+list_of(map(raw_bytes,tokens))+"\n"+
            "  values := "+list_of(f"({q.numerator}/{q.denominator}:ℚ)" for q in values)+"\n"+
            "  decoded := by decide +kernel\n"+
            "  bytes := "+raw_bytes(text)+"\n"+
            "  tokenized := by decide +kernel\n")


def decoded_module(name, raw, source):
    """
    Generate defining input data and the proof that flattening its chunks recovers the original
    byte sequence. Hash strings identify provenance; decoded and tokenized fields carry the
    mathematical checks.
    """
    text = raw.decode("ascii")
    chunks = list(number_chunks(text))
    out = ("import «2610.05164v2».Certificates.ExactNumbers\n\n" +
           "/-! Generated by Scripts/ReferenceInputs.py. Do not edit.\n" +
           "Exact defining inputs only; no saved numerical reports are premises. -/\n" +
           f"namespace «2610.05164v2».Certificates.DualInputs.{name}\n" +
           "open «2610.05164v2».Certificates\nset_option autoImplicit false\n" +
           "set_option warningAsError true\nset_option maxRecDepth 200000\n" +
           "set_option maxHeartbeats 0\n\n" +
           "def archiveSHA256 : String := " + literal(source["archive_sha256"]) + "\n" +
           "def payloadSHA256 : String := " + literal(hashlib.sha256(raw).hexdigest()) + "\n\n")
    for i, chunk in enumerate(chunks):
        out += f"def block{i} : DecodedBytes where\n" + decoded_fields(chunk) + "\n"
    out += "def chunks : List DecodedBytes := " + list_of(f"block{i}" for i in range(len(chunks))) + "\n"
    out += "def sourceBytes : List ℕ := " + raw_bytes(text) + "\n"
    out += "theorem source_bytes : (chunks.map DecodedBytes.bytes).flatten=sourceBytes := by decide +kernel\n"
    out += "def values : List ℚ := chunks.flatMap DecodedBytes.values\n"
    out += f"end «2610.05164v2».Certificates.DualInputs.{name}\n"
    return out


def reference_model_module():
    """
    Generate the five-pole rational reference and sigma/base/omega parameters from decoded
    inputs. Positivity is checked by kernel reduction; numerical observations are not assumed.
    """
    return """import «2610.05164v2».Certificates.DualInputs.Reference
import «2610.05164v2».DualCertificate.RationalReference

/-! Generated exact reference model, shared by source ODE verification and
Definition 7. No numerical observation is included in the defining inputs. -/
namespace «2610.05164v2».Certificates.DualInputs
open «2610.05164v2».DualCertificate
set_option autoImplicit false
set_option warningAsError true
set_option maxHeartbeats 0

def reference : RationalReference where
  count := 5
  p₀ := Reference.values[5]?.getD 0
  p i := Reference.values[6+2*i.val]?.getD 0
  ζ i := Reference.values[7+2*i.val]?.getD 0
  p₀_pos := by decide +kernel
  p_pos := by intro i; fin_cases i <;> decide +kernel
  ζ_pos := by intro i; fin_cases i <;> decide +kernel

def sigma : ℚ := Reference.values[1]?.getD 0
def base : ℚ := Reference.values[2]?.getD 0
def omega : ℚ := Reference.values[3]?.getD 0
theorem reference_signs : 0<sigma ∧ 0<base ∧ 0≤omega := by decide +kernel
end «2610.05164v2».Certificates.DualInputs
"""


def main():
    """
    Load the pinned reference member, validate its layout, and install or compare the two
    defining-input modules. Check mode compares all executable witness source without replaying
    numerical certificates.
    """
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--offline',action='store_true')
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    source=load_source(ROOT/'2610.05164v2/Certificates/Source.json')
    receipt=fetch(source,ROOT/'.lake/certificates/2610.05164v2',args.offline)
    archive=Path(receipt['archive'])
    payload,_=prepare_payload(archive,archive.parent)
    raw=(payload/'embedded/reference/reference.txt').read_bytes()
    tokens=numeric_tokens(raw.decode('ascii'))
    if len(tokens)!=19 or tokens[0]!='1' or tokens[4]!='11' or tokens[16]!='2':
        raise ValueError('Unexpected exact reference format')
    outputs={'Reference.lean':decoded_module('Reference',raw,source),
             'ReferenceModel.lean':reference_model_module()}
    for name,text in outputs.items():
        target=ROOT/'2610.05164v2/Certificates/DualInputs'/name
        install_source(target,text,args.check)
    print('Reference input provenance checked; no numerical claim inferred.')


if __name__=='__main__':main()
